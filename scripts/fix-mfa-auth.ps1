    Invoke-ServerPatch -Marker "require('./routes/mfa')" -InsertAfter "app.use('/api/support',     require('./routes/support'))" -PatchBlock $mfaPatch | Out-Null
} else {
    Invoke-ServerPatch -Marker "require('./routes/mfa')" -InsertAfter "app.use('/api/admin',       require('./routes/health'))" -PatchBlock $mfaPatch | Out-Null
}

Write-FixReport -Summary 'Added MFA database columns, TOTP setup/verify routes, recovery codes, and admin MFA enforcement middleware.' -NextSteps @(
    'Apply migration: psql -f migrations/20260624_mfa_auth.sql'
    'Install otplib for production-grade TOTP verification'
    'Add MFA enrollment UI in admin profile settings'
)

